function pageProgressAt(time, aspect, clock) {
  if (time === 43) return 0.825
  const frame = clock.createPrivateInspectionSample()
  let lo = 0.905, hi = 0.94
  for (let i = 0; i < 55; i++) {
    const mid = (lo + hi) / 2
    if (clock.samplePrivateInspection(mid, aspect, frame).subjectTime < time) lo = mid
    else hi = mid
  }
  return 0.62 + (lo + hi) / 2 - 0.735
}
