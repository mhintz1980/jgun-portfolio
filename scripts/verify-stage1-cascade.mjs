function projectedRect(proof, cascade) {
  const ndcs = cascade ? (proof.rectangles ?? []).filter(r => r.opacity > 0 && r.vertices > 0).map(r => r.ndc) : [proof.contact?.ndc]
  if (!proof.canvas || !ndcs.length || !ndcs.every(validNdc)) return null
  const ndc = [Math.min(...ndcs.map(r => r[0])), Math.min(...ndcs.map(r => r[1])), Math.max(...ndcs.map(r => r[2])), Math.max(...ndcs.map(r => r[3]))]
  const c = proof.canvas
  return { left: c.left + (ndc[0] + 1) * c.width / 2, top: c.top + (1 - ndc[3]) * c.height / 2,
    right: c.left + (ndc[2] + 1) * c.width / 2, bottom: c.top + (1 - ndc[1]) * c.height / 2 }
}
async function domClearance(page, subject) {
  return page.evaluate(subject => {
    const selector = '[data-shaft-caption], .torque-chapter__title, .torque-chapter__lede, .torque-chapter__body, .torque-page button, .torque-page input, .torque-page select, .torque-page summary, .torque-page [role="button"], .torque-inspection__panel'
    const visible = element => {
      let node = element
      while (node instanceof Element) {
        const style = getComputedStyle(node)
        const bounds = node.getBoundingClientRect()
        const clippedSr = bounds.width <= 1 && bounds.height <= 1
          && (style.clipPath !== 'none' || style.clip !== 'auto' || style.overflow === 'hidden')
        if (style.display === 'none' || style.visibility !== 'visible' || Number(style.opacity) <= 0.01
          || clippedSr
          || node.matches('.torque-sr, .shaft-visually-hidden')) return false
        node = node.parentElement
      }
      return true
    }
    const elements = [...document.querySelectorAll(selector)].filter(visible).map(element => {
      const r = element.getBoundingClientRect()
      return { tag: element.tagName, className: String(element.className), text: element.textContent?.trim().slice(0, 180),
        left: Math.max(0, r.left), top: Math.max(0, r.top), right: Math.min(innerWidth, r.right), bottom: Math.min(innerHeight, r.bottom) }
    }).filter(r => r.right > r.left && r.bottom > r.top)
    const overlaps = subject ? elements.filter(r => r.left < subject.right + 8 && r.right > subject.left - 8
      && r.top < subject.bottom + 8 && r.bottom > subject.top - 8) : []
    return { subject, marginPixels: 8, elements, overlaps, pass: !!subject && elements.length > 0 && overlaps.length === 0 }
  }, subject)
}
function cleanClip(subject, viewport, aspect) {
  if (!subject || !Object.values(subject).every(Number.isFinite)) throw new Error('Missing clean-still subject bounds')
  const width = subject.right - subject.left, height = subject.bottom - subject.top
  if (!(width > 0 && height > 0)) throw new Error('Empty clean-still subject bounds')
  let w = Math.max(width * 1.25 + 32, (height * 1.25 + 32) * aspect)
  w = Math.min(w, viewport.width, viewport.height * aspect)
  // Integer 8x5 or 1x1 pixel blocks preserve the exported image aspect exactly.
  const quantum = aspect === 1 ? 1 : 8
  w = Math.floor(w / quantum) * quantum
  const h = w / aspect
  const x = Math.floor(Math.max(0, Math.min(viewport.width - w, (subject.left + subject.right - w) / 2)))
  const y = Math.floor(Math.max(0, Math.min(viewport.height - h, (subject.top + subject.bottom - h) / 2)))
  if (subject.left < x - 1 || subject.right > x + w + 1 || subject.top < y - 1 || subject.bottom > y + h + 1) {
    throw new Error('Subject does not fit the required clean-still aspect; camera/crop needs correction')
  }
  return { x, y, width: w, height: h }
}
async function cleanStill(page, still, result, clock, aspect) {
  const sample = await seek(page, still.time, aspect, clock)
  const proof = await subjectProof(page, true)
  const subject = projectedRect(proof, still.name === 'driveline-cascade')
  const clip = cleanClip(subject, result.viewport, result.name === 'narrow' ? 1 : 8 / 5)
  let style
  try {
    style = await page.addStyleTag({ content: 'body * { visibility: hidden !important; } body canvas { visibility: visible !important; }' })
    const png = await page.screenshot({ clip, timeout: shotTimeout })
    const bytes = await encodeWebp(page, png)
    return { bytes, metadata: { requestedTime: still.time, subjectTime: sample.subjectTime, source: 'Separate UI-hidden screenshot; never converted from debug PNG',
      uiHidden: true, clip, aspect: result.name === 'narrow' ? '1:1' : '8:5', subject, contact: proof.contact,
      rectangles: proof.rectangles, cleanPngSha256: sha256(png) } }
  } finally {
    if (style) await style.evaluate(element => element.remove())
  }
}
