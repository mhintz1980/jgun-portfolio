async function encodeWebp(page, png) {
  const data = await page.evaluate(async base64 => {
    const bitmap = await createImageBitmap(await (await fetch(`data:image/png;base64,${base64}`)).blob())
    try {
      const canvas = new OffscreenCanvas(bitmap.width, bitmap.height)
      const ctx = canvas.getContext('2d')
      if (!ctx) throw new Error('No 2D canvas for WebP encoding')
      ctx.drawImage(bitmap, 0, 0)
      const blob = await canvas.convertToBlob({ type: 'image/webp', quality: 0.92 })
      if (blob.type !== 'image/webp') throw new Error(`WebP encoding returned ${blob.type}`)
      return await new Promise((resolve, reject) => {
        const reader = new FileReader()
        reader.onload = () => resolve(reader.result)
        reader.onerror = () => reject(new Error('WebP FileReader failed'))
        reader.readAsDataURL(blob)
      })
    } finally { bitmap.close() }
  }, png.toString('base64'))
  if (typeof data !== 'string' || !data.startsWith('data:image/webp;base64,')) throw new Error('Invalid encoded WebP')
  return Buffer.from(data.slice('data:image/webp;base64,'.length), 'base64')
}

