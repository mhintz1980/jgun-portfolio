function requireProbe(sample) {
  const s = sample.stage1
  if (!s || !Number.isFinite(sample.subjectTime) || !Number.isFinite(sample.cameraTime)) throw new Error('Missing inspection clock or stage1 probe')
  for (const key of ['cascadePresent', 'cascadeAlpha', 'cascadeOffsetZ', 'cascadeRotZ']) {
    if (!Array.isArray(s[key]) || s[key].length !== 8) throw new Error(`47-v1 requires ${key}[8]`)
    if (key === 'cascadePresent' ? s[key].some(x => typeof x !== 'boolean') : s[key].some(x => !Number.isFinite(x))) {
      throw new Error(`Invalid ${key} values`)
    }
  }
  for (const key of ['slideProgress', 'sunRotZ', 'carrierRotZ', 'planetRotZ', 'meshPhaseError', 'housingGhostAlpha',
    'datumPulseAlpha', 'legacyHousingAlpha', 'legacyBearingAlpha', 'legacyRingAlpha', 'contactGlintYmm', 'contactGlintMix', 'housingWitnessAlpha']) {
    if (!Number.isFinite(s[key])) throw new Error(`Missing/nonfinite stage1.${key}`)
  }
  for (const key of ['section', 'bulletTimeActive', 'gearMeshClean']) if (typeof s[key] !== 'boolean') throw new Error(`Missing stage1.${key}`)
}

